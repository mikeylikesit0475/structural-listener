"""Piezo sensor model: material attenuation, additive noise, per-channel gain mismatch.

Wraps the raw FDTD solver output (out-of-plane velocity at each sensor cell, in m/s) into
realistic sensor signals. Three effects are modelled, all cited in ``docs/sources.md``:

1. **Material attenuation** \u2014 frequency-dependent damping along the propagation path.
   Applied as a per-channel first-order IIR low-pass whose cutoff depends on the
   source-to-sensor distance, approximating the hysteretic damping model in [Grosse].
2. **Additive noise** \u2014 white Gaussian (thermal/Sensor electronics) plus 1/f (pink)
   component, per channel. The 1/f part is generated by累积ating filtered white noise.
3. **Per-channel gain mismatch** \u2014 each sensor channel has a slightly different
   preamp gain (\u00b12%), drawn once and held fixed for a run.

Geometric spreading (1/sqrt(r) in a 2D plate) is already in the FDTD propagation \u2014 the
solver naturally attenuates with distance \u2014 so it is NOT re-applied here.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from structural_listener.sim.fdtd import SimResult


@dataclass(frozen=True, slots=True)
class SensorModelConfig:
    """Parameters for the sensor model. See ``docs/sources.md`` for citations."""

    # White noise floor, in m/s (velocity at the sensor). Roughly -60 dB rel 1 m/s.
    noise_rms_white: float = 1.0e-6
    # 1/f noise component amplitude at 1 Hz, in m/s.
    noise_pink_at_1hz: float = 5.0e-7
    # Per-channel gain mismatch: gain = 1 + U(-spread, +spread).
    gain_spread: float = 0.02
    # Material attenuation coefficient at 100 kHz, in Np/m. Aluminium Q~1000 at 100 kHz
    # [Grosse] gives alpha ~ 1 Np/m at 100 kHz; we scale as f^2 (hysteretic damping model).
    attenuation_coeff_at_100khz_per_m: float = 1.0
    # Reference frequency for the attenuation coefficient (Hz).
    attenuation_ref_freq_hz: float = 100.0e3
    # Attenuation frequency exponent: alpha(f) = alpha_0 * (f/f0)^exponent. 2.0 is the
    # standard hysteretic-damping scaling for metals [Grosse].
    attenuation_freq_exponent: float = 2.0
    # RNG seed for reproducible noise/gain. None = non-deterministic.
    seed: int | None = 42


def _pink_noise(n: int, rng: np.random.Generator, amplitude_at_1hz: float, dt: float) -> np.ndarray:
    """Generate 1/f noise by integrating filtered white noise (Voss-McCartney approximation).

    The amplitude at 1 Hz is normalised to ``amplitude_at_1hz``; other frequencies follow
    the 1/f power law. This is a standard cheap approximation \u2014 not a precision 1/f
    generator, but adequate for sensor-noise modelling.
    """
    white = rng.standard_normal(n)
    # Integrate white noise to get 1/f^2 (Brownian), then take a fractional derivative
    # back toward 1/f by filtering. Simpler: cumulative sum gives 1/f^2; we want 1/f, so
    # use a half-integration via a first-order filter on the cumulative sum.
    cumsum = np.cumsum(white)
    # High-pass at f_min = 1/(n*dt) to keep the signal finite.
    f_min = 1.0 / (n * dt)
    # First-order high-pass.
    alpha = 2.0 * np.pi * f_min * dt / (1.0 + 2.0 * np.pi * f_min * dt)
    filtered = np.empty(n)
    prev = 0.0
    for k in range(n):
        prev = (1.0 - alpha) * prev + alpha * (cumsum[k] - (cumsum[k - 1] if k > 0 else 0.0))
        filtered[k] = cumsum[k] - prev
    # Normalise so the amplitude at 1 Hz matches the target.
    # The PSD at 1 Hz of the filtered signal is ~ unit; scale by amplitude_at_1hz.
    current_rms = float(np.std(filtered))
    if current_rms > 0.0:
        filtered = filtered * (amplitude_at_1hz / current_rms)
    return filtered


def _apply_frequency_dependent_attenuation(
    signal: np.ndarray,
    distance_m: float,
    sample_rate_hz: float,
    coeff_at_ref: float,
    ref_freq_hz: float,
    freq_exponent: float,
) -> np.ndarray:
    """Apply distance- and frequency-dependent material attenuation in the frequency domain.

    Model: amplitude(f, r) = exp(-alpha(f) * r), with alpha(f) = alpha_0 * (f/f0)^exponent.
    This is the hysteretic-damping model for metals [Grosse]; alpha_0 = 1 Np/m at 100 kHz
    for aluminium with Q ~ 1000. Applied per-channel in the FFT domain.
    """
    n = signal.shape[0]
    spec = np.fft.rfft(signal)
    freqs = np.fft.rfftfreq(n, d=1.0 / sample_rate_hz)
    alpha = coeff_at_ref * (freqs / ref_freq_hz) ** freq_exponent
    spec_att = spec * np.exp(-alpha * distance_m)
    out: np.ndarray = np.fft.irfft(spec_att, n=n)
    return out


def dt_eff(sample_rate_hz: float) -> float:
    """Return the sample interval from the sample rate."""
    return 1.0 / sample_rate_hz


def apply_sensor_model(
    sim_result: SimResult,
    source_xy_m: tuple[float, float] | None = None,
    sensor_positions_m: tuple[tuple[float, float], ...] | None = None,
    config: SensorModelConfig | None = None,
) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    """Apply the sensor model to a SimResult and return (waveforms, metadata).

    Args:
        sim_result: output of ``simulate``.
        source_xy_m: source position for distance-dependent attenuation. If None, uses
            ``sim_result.true_source_xy_m``.
        sensor_positions_m: sensor positions for distance computation. If None, uses the
            default corner layout from ``SensorLayout``.
        config: sensor model parameters. If None, uses ``SensorModelConfig()`` defaults.

    Returns:
        (waveforms, metadata) where waveforms is (n_sensors, n_samples) in m/s and
        metadata contains the per-channel gains and distances for reproducibility.

    """
    cfg = config or SensorModelConfig()
    src = source_xy_m or sim_result.true_source_xy_m
    if sensor_positions_m is None:
        from structural_listener.sim.config import SensorLayout

        sensor_positions_m = SensorLayout().positions_m

    rng = np.random.default_rng(cfg.seed)
    n_sensors, n_samples = sim_result.waveforms.shape
    dt = 1.0 / sim_result.sample_rate_hz

    gains = np.asarray(
        1.0 + rng.uniform(-cfg.gain_spread, cfg.gain_spread, size=n_sensors), dtype=np.float64
    )
    distances: np.ndarray = np.array(
        [float(np.hypot(s[0] - src[0], s[1] - src[1])) for s in sensor_positions_m]
    )

    out = np.empty((n_sensors, n_samples), dtype=np.float64)
    for ch in range(n_sensors):
        # 1. Material attenuation: frequency- and distance-dependent, in the FFT domain.
        attenuated = _apply_frequency_dependent_attenuation(
            sim_result.waveforms[ch],
            float(distances[ch]),
            sim_result.sample_rate_hz,
            cfg.attenuation_coeff_at_100khz_per_m,
            cfg.attenuation_ref_freq_hz,
            cfg.attenuation_freq_exponent,
        )
        # 2. Per-channel gain.
        gained: np.ndarray = attenuated * float(gains[ch])
        # 3. Additive noise: white + pink.
        white = rng.standard_normal(n_samples) * cfg.noise_rms_white
        pink = _pink_noise(n_samples, rng, cfg.noise_pink_at_1hz, dt)
        out[ch] = gained + white + pink

    metadata: dict[str, np.ndarray] = {
        "gains": gains,
        "distances_m": distances,
        "source_xy_m": np.array(src),
    }
    return out, metadata
